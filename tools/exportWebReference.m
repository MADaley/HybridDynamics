%% EXPORTWEBREFERENCE  Export settings, presets and reference results for the web page.
% Purpose : write the SLIP and ball-in-a-box settings, the presets, the
%           same-speed stiffness family and a set of reference cases from
%           the MATLAB toolkit, so the interactive page uses the same
%           numbers and its tests can check its simulator against MATLAB.
% Outputs : interactive/data/reference.json (read by the JavaScript tests)
%           interactive/js/reference.js   (the same data, loaded by the page)
% Run     : after tools/slip_computePresets.m, and after any model change.

clear; close all;
toolDir = fileparts(mfilename('fullpath'));
root = fullfile(toolDir, '..');
run(fullfile(root, 'setupHybridDynamics.m'));

%% ===== USER SETTINGS: stiffness family shown on the page =====
kValues = (6:1:35) * 1000;        % leg stiffness values (N/m)
footClearance = 0.05;             % minimum foot height at apex (m), as the presets

%% 1. Settings and presets
[p, apex, spec, presets] = slip_defaults("human");
ref.generatedBy = "tools/exportWebReference.m";
ref.slip.spec = table2struct(spec);
ref.slip.presets = table2struct(presets);
[pb, xb, specBall] = ballInBox_defaults();
ref.ball.spec = table2struct(specBall);

%% 2. Reference cases for the SLIP simulator
cases = {};
for i = 1:height(presets)
    [q, a] = slip_defaults(presets.name(i));
    cases{end+1} = slipCase("preset " + presets.name(i), q, a, true); %#ok<SAGROW>
end
% Off the periodic gait: apex 2 cm high, five strides.
a2 = apex; a2.y = apex.y + 0.02;
cases{end+1} = slipCase("human, apex +2 cm", p, a2, false, 5);
% Swing-leg retraction at 60 deg/s from the baseline apex state.
q = p; q.retractionDegPerS = 60;
cases{end+1} = slipCase("human, retraction 60 deg/s", q, apex, false, 3);
% Fast retraction that carries the foot below the ground and back up.
legVel = 3 * sqrt(9.81 / 0.667);
q = struct('m', 80, 'k', 50000, 'L0', 1, 'g', 9.81, ...
    'legAngleDeg', 180 - rad2deg(2.754657), 'retractionDegPerS', rad2deg(legVel));
cases{end+1} = slipCase("fast retraction, foot dips below ground", q, struct('y', 0.998622, 'vx', 5), false, 3);
% Baseline gait with a fixed leg angle (no retraction).
q = p; q.legAngleDeg = presets.touchdownAngleDeg(presets.name == "human"); q.retractionDegPerS = 0;
cases{end+1} = slipCase("human, fixed leg angle", q, apex, true);
% Failures
q = p; q.legAngleDeg = 85;
cases{end+1} = slipCase("leg too steep for the apex", q, apex, false, 1);
q = p; q.k = 3000;
cases{end+1} = slipCase("leg too compliant", q, apex, false, 1);
q = p; q.legAngleDeg = 40;
cases{end+1} = slipCase("leg too shallow", q, apex, false, 1);
% Touchdown with the leg behind vertical and the body moving away: missed stance.
q = struct('m', 80, 'k', 12000, 'L0', 1, 'g', 9.81, 'legAngleDeg', 100, 'retractionDegPerS', 0);
cases{end+1} = slipCase("leg behind vertical, missed stance", q, ...
    struct('y', sind(100) + 0.01, 'vx', 5), false, 1);
ref.slip.cases = [cases{:}];

%% 3. Same-speed stiffness family (with the drop test)
target = struct('meanSpeed', presets.meanSpeed(1), 'hold', "stepFrequency", ...
    'stepFrequency', presets.stepFrequency(1));
T = slip_stiffnessFamily(struct('p', p, 'y', apex.y, 'vx', apex.vx), kValues, ...
    target, struct('terrain', true, 'footClearance', footClearance));
ref.slip.family.target = target;
ref.slip.family.footClearance = footClearance;
ref.slip.family.referenceRetractionDegPerS = p.retractionDegPerS;

%% 3b. Retraction for a foot clearance (reference for the web function)
q = p; q.legAngleDeg = presets.touchdownAngleDeg(presets.name == "human"); q.retractionDegPerS = 0;
[q8, info8] = slip_retractionForClearance(q, apex, 0.08);
ref.slip.clearanceCase = struct('p', q, 'apex', apex, 'clearance', 0.08, ...
    'legAngleDeg', q8.legAngleDeg, 'retractionDegPerS', q8.retractionDegPerS, ...
    'fallTime', info8.fallTime, 'touchdownAngleDeg', info8.touchdownAngleDeg);
ref.slip.family.rows = table2struct(T);

%% 4. Ball in a box
r = hde.simulate(ballInBox_model(pb), xb, hde.solverDefaults(struct('timeLimit', 6)));
ref.ball.x0 = xb';
ref.ball.events = struct('time', num2cell(r.events.time), 'guard', cellstr(r.events.guard));

%% 5. Write JSON and the JavaScript copy
txt = jsonencode(ref, 'PrettyPrint', true);
dataDir = fullfile(root, 'interactive', 'data');
if ~exist(dataDir, 'dir'), mkdir(dataDir); end
writeText(fullfile(dataDir, 'reference.json'), txt);
writeText(fullfile(root, 'interactive', 'js', 'reference.js'), ...
    "/* Generated by tools/exportWebReference.m. Do not edit by hand. */" + newline + ...
    "var HDS_REFERENCE = " + txt + ";" + newline);
fprintf('Wrote %d SLIP cases, %d family rows and %d ball events.\n', ...
    numel(ref.slip.cases), height(T), height(r.events));

%% ===== Local functions =====
function c = slipCase(name, p, apex, periodic, nStrides)
% Simulate from apex and record what the JavaScript simulator must match.
if nargin < 5, nStrides = 1; end
c.name = name;
c.p = p;
c.apex = apex;
model = slip_model(p);
s = [apex.y; apex.vx];
seq = struct('y', apex.y, 'vx', apex.vx);
reason = "cycleLimit";
for i = 1:nStrides
    [sNext, info] = slip_returnMap(p, s, model);
    if i == 1
        r = info.result;
        c.firstStride.exitReason = info.exitReason;
        c.firstStride.events = struct('time', num2cell(r.events.time), ...
            'guard', cellstr(r.events.guard));
    end
    if any(isnan(sNext))
        reason = info.exitReason;
        break
    end
    s = sNext;
    seq(end+1) = struct('y', s(1), 'vx', s(2)); %#ok<AGROW>
end
c.exitReason = reason;
c.apexSequence = seq;
c.metrics = [];
c.lambda = [];
c.maxDrop = [];
c.dropFailure = "";
c.nmd = [];
if periodic
    M = slip_metrics(p, [apex.y; apex.vx]);
    keep = ["period" "contactTime" "flightTime" "stepLength" "meanSpeed" ...
        "touchdownAngleDeg" "takeoffAngleDeg" "legCompression" "peakLegForceBW" ...
        "peakVerticalForceBW" "peakBrakingForceBW" "comDropStance" ...
        "peakElasticEnergy" "positiveWorkPerDistance" "forceTimeCostIndex"];
    for f = keep
        c.metrics.(f) = M.(f);
    end
    S = slip_stability(p, [apex.y; apex.vx], struct('jacobian', false));
    c.lambda = S.lambda;
    c.maxDrop = S.maxDrop;
    c.dropFailure = S.dropFailure;
    D = slip_normalizedMaxDrop(p, apex, struct('referenceRetractionDegPerS', 100));
    c.nmd = struct('estimate', D.estimateNMD, 'simulated', D.simulatedNMD, ...
        'atReference', D.estimateDropAtReference / p.L0, 'referenceRetractionDegPerS', 100);
end
end

function writeText(file, txt)
fid = fopen(file, 'w');
fwrite(fid, txt, 'char');
fclose(fid);
end
